function f = bivariate_ramps(imax,jmax,i_vals,i_breaks,j_vals,j_breaks)
f_i = @(i) smooth_ramps((i-1)/(imax-1),i_breaks,i_vals);
f_j = @(j) smooth_ramps((j-1)/(jmax-1),j_breaks,j_vals);
f = @(i,j) f_i(i).*f_j(j);
end